"""Inventory native imports and address-sensitive operations in recovered HSP source."""
import argparse
from collections import Counter
import hashlib
import json
from pathlib import Path
import re


def code_only(line):
    result = []
    quoted = False
    escaped = False
    for character in line:
        if quoted:
            if character == '"' and not escaped:
                quoted = False
            escaped = character == "\\" and not escaped
            result.append(" ")
        elif character == '"':
            quoted = True
            result.append(" ")
        elif character == ";":
            break
        else:
            result.append(character)
    return "".join(result)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", type=Path, default=Path("recovered/game/port-source.hsp"))
    args = parser.parse_args()
    raw = args.source.read_bytes()
    lines = raw.decode("cp932").splitlines()
    libraries = []
    current = None
    tokens = Counter()
    sensitive = {name: [] for name in ("varptr", "dupptr", "mref", "memcpy", "call", "newcom", "querycom", "comres", "sendmsg", "devinfo")}
    for number, line in enumerate(lines, 1):
        library = re.match(r'\s*#uselib\s+"([^"]+)"', line, re.I)
        if library:
            current = {"library": library[1], "line": number, "imports": []}
            libraries.append(current)
        function = re.match(r'\s*#(cfunc|func)\s+(\w+)\s+"([^"]+)"(.*)', line, re.I)
        if function:
            if current is None:
                raise ValueError(f"Import before library on line {number}")
            current["imports"].append({"name": function[2], "export": function[3],
                                       "declaration_kind": function[1], "parameters": function[4].strip(),
                                       "line": number})
        if not line.lstrip().startswith("#"):
            identifiers = re.findall(r"[a-z_][a-z0-9_@]*", code_only(line).lower())
            tokens.update(identifiers)
            for name in sensitive:
                if name in identifiers:
                    sensitive[name].append(number)
    for library in libraries:
        for function in library["imports"]:
            function["references"] = tokens[function["name"].lower()]
        library["references"] = sum(f["references"] for f in library["imports"])
    report = {"source_sha256": hashlib.sha256(raw).hexdigest(), "source_lines": len(lines),
              "library_blocks": len(libraries), "import_declarations": sum(len(x["imports"]) for x in libraries),
              "libraries": libraries, "address_sensitive_operations": sensitive,
              "interpretation": "Lexical references, not a call graph or proof of runtime reachability."}
    Path("reports/platform-calls.json").write_text(json.dumps(report, indent=2) + "\n", encoding="utf-8")
    summary = ["# Direct port: native dependency inventory", "",
               "Generated by `python tools/audit_platform_calls.py`. Counts are lexical references, not runtime calls.", "",
               "| Library | Imports | References |", "| --- | ---: | ---: |"]
    summary += [f"| `{entry['library']}` | {len(entry['imports'])} | {entry['references']} |" for entry in libraries]
    summary += ["", "Address-sensitive HSP operations require review when moving from x86 to arm64:", ""]
    summary += [f"- `{name}`: {len(positions)} source lines." for name, positions in sensitive.items() if positions]
    Path("docs/native-dependencies.md").write_text("\n".join(summary) + "\n", encoding="utf-8")
    print(f"Audited {len(lines):,} lines, {len(libraries)} library blocks, {report['import_declarations']} imported functions")


if __name__ == "__main__":
    main()
