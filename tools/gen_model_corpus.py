"""Write a ZGP reference script that loads every animated model of the game.

The game's model3dread calls loadax for each model/<name>/ holding both
model.x and model.mqx, after chdir into that directory (recovered.hsp line
4180). The script registers CSMesh with anilibload, creates the device as
the game does, then loads each model the same way into its own slot. Run it
through the Windows reference harness (direct/tests/zgp_windows_reference.cpp)
from the installation directory; direct/tests/d3dx_mesh_test.cpp compares
the native D3DX mesh loading with the original's trace.
"""
import argparse
from pathlib import Path

HEADER = """_anilibload@16 i:0 s:plugin/CSMesh.dll i:256
_createdx@16
_setaspect@16 i:1777
_setmaxsurf@16 i:16 i:256
_setmaxunit@16 i:256 i:256 i:128 i:32
_setbmscr@16 bmscr
_createdevm@16 v:0,0,0,960,540,0,0,0,0,0,0
_set3d@16 i:0 i:0 i:131070 i:6553500"""


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--installation", type=Path, default=Path("Corpse Party 2 Dead Patient"))
    parser.add_argument("--output", type=Path, default=None)
    parser.add_argument("--draw", action="store_true",
                        help="also place each model, play it and draw two frames with objdraw "
                             "(direct/tests/zgp/model-draw-corpus.script, compared by zgp_trace_test)")
    args = parser.parse_args()
    if args.output is None:
        args.output = Path("direct/tests/zgp/model-draw-corpus.script" if args.draw else "direct/tests/zgp/model-corpus.script")
    models = [d.name for d in sorted((args.installation / "model").iterdir())
              if (d / "model.x").is_file() and (d / "model.mqx").is_file()]
    for name in models:
        name.encode("ascii")  # the harness passes @chdir paths to SetCurrentDirectoryA unchanged
    what = "loaded with loadax as model3dread does"
    if args.draw:
        what += ", then placed, played and drawn twice through CSMesh"
    lines = ["# Every animated model (%d), %s." % (len(models), what),
             "# Generated by tools/gen_model_corpus.py%s; run from the installation directory."
             % (" --draw" if args.draw else ""), HEADER]
    if args.draw:
        lines += ["_setfovy@16 i:15", "_cat@16 i:70 i:1400000 i:1500000"]
    for n, name in enumerate(models, 1):
        lines += ["@chdir model/%s" % name, "_loadax@16 i:%d s:model.x i:0" % n, "@chdir ../.."]
        if args.draw:
            lines += ["_objameshset@16 i:%d i:%d" % (n, n), "_objplay@16 i:%d i:%d i:-1" % (n, 37 * n),
                      "_objdraw@16 i:%d i:1 i:0" % n, "_objdraw@16 i:%d i:1 i:0" % n]
    args.output.write_text("\n".join(lines) + "\n", encoding="ascii", newline="\n")
    print("%s: %d models" % (args.output, len(models)))


if __name__ == "__main__":
    main()
