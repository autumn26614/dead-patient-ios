"""Write a ZGP reference script that loads every image file of the game.

Each .tga, .bmp and .png under the installation is loaded with texload twice:
with the color key the game uses most (textrans 0, opaque black) and with
the key disabled (textrans -1). Run the script through the Windows reference
harness (direct/tests/zgp_windows_reference.cpp) and through
direct/tests/zgp_trace_test.cpp from the installation directory; every
created texture's levels are compared texel for texel.
"""
import argparse
from pathlib import Path

STARTUP = Path(__file__).resolve().parent.parent / "direct/tests/zgp/startup.script"


def escape(path):
    out = []
    for byte in path.encode("cp932"):
        out.append("%%%02X" % byte if byte <= 0x20 or byte >= 0x7f or byte == ord("%") else chr(byte))
    return "".join(out)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--installation", type=Path, default=Path("Corpse Party 2 Dead Patient"))
    parser.add_argument("--output", type=Path, default=Path("direct/tests/zgp/texture-corpus.script"))
    args = parser.parse_args()
    images = sorted(p.relative_to(args.installation).as_posix() for p in args.installation.rglob("*")
                    if p.is_file() and p.suffix.lower() in (".tga", ".bmp", ".png"))
    lines = ["# Every game image (%d files), loaded with textrans 0 and textrans -1." % len(images),
             "# Generated by tools/gen_texture_corpus.py; run from the installation directory."]
    lines += [line for line in STARTUP.read_text().splitlines() if line and not line.startswith("#")]
    for key in ("0", "-1"):
        lines.append("_textrans@16 i:%s" % key)
        lines += ["_texload@16 i:1 s:%s" % escape(path) for path in images]
    args.output.write_text("\n".join(lines) + "\n", encoding="ascii", newline="\n")
    print("%s: %d images, %d loads" % (args.output, len(images), 2 * len(images)))


if __name__ == "__main__":
    main()
