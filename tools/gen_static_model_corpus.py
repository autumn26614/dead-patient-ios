"""Write a ZGP reference script that loads every static model of the game.

The game's model3dread calls loadx for each model/<name>/ holding model.x but
no model.mqx, after chdir into that directory, then objmeshset (recovered.hsp
line 4205). Mesh and object numbers continue after the animated models,
from model_mesh_top + meshno and model_obj_top + meshno (50 and 150, meshno
from 113). The script creates the device as the game does, then loads each
model the same way and dumps the mesh and object entries. Run it through the
Windows reference harness (direct/tests/zgp_windows_reference.cpp) from the
installation directory; direct/tests/zgp_trace_test.cpp compares the native
transcription with the original's trace.
"""
import argparse
from pathlib import Path

HEADER = """_createdx@16
_setaspect@16 i:1777
_setmaxsurf@16 i:16 i:256
_setmaxunit@16 i:4096 i:4096 i:4096 i:4096
_setbmscr@16 bmscr
_createdevm@16 v:0,0,0,960,540,0,0,0,0,0,0
_set3d@16 i:0 i:0 i:131070 i:6553500"""

MODEL_MESH_TOP, MODEL_OBJ_TOP, FIRST_STATIC = 50, 150, 113


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--installation", type=Path, default=Path("Corpse Party 2 Dead Patient"))
    parser.add_argument("--output", type=Path, default=Path("direct/tests/zgp/static-model-corpus.script"))
    args = parser.parse_args()
    models = [d.name for d in sorted((args.installation / "model").iterdir())
              if (d / "model.x").is_file() and not (d / "model.mqx").is_file()]
    for name in models:
        name.encode("ascii")  # the harness passes @chdir paths to SetCurrentDirectoryA unchanged
    lines = ["# Every static model (%d), loaded with loadx and objmeshset as model3dread does." % len(models),
             "# Generated by tools/gen_static_model_corpus.py; run from the installation directory.", HEADER]
    for n, name in enumerate(models, FIRST_STATIC):
        mesh, obj = MODEL_MESH_TOP + n, MODEL_OBJ_TOP + n
        lines += ["@chdir model/%s/" % name, "_loadx@16 i:%d s:model.x" % mesh, "@chdir ../..",
                  "_objmeshset@16 i:%d i:%d" % (obj, mesh), "@mesh %d" % mesh, "@meshsurf %d" % mesh,
                  "@obj %d" % obj]
    args.output.write_text("\n".join(lines) + "\n", encoding="ascii", newline="\n")
    print("%s: %d models" % (args.output, len(models)))


if __name__ == "__main__":
    main()
